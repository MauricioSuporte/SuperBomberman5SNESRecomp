#!/usr/bin/env python3
"""Write src/rom_probes.h from the supported ROM. Addresses and one CRC per mod.

Every cartridge address a mod names in its source becomes a four-byte site. A ROM
hosts the mod only if the CRC of all its sites matches. Rerun after adding a hook.
"""
from __future__ import annotations

import hashlib
import pathlib
import re
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
EXTRA = ('extra_characters_mod.c', 'subordinate_mod.c', 'special_abilities.c', 'clock_mounts.c', 'sb5_sound.c')
# Plugin id -> sources holding the sites it relies on.
PLUGINS = {
    'superbomberman5.battle.variants': ('battle_variants_mod.c',),
    'superbomberman5.bomber-kings.characters': EXTRA,
    'superbomberman5.boss.rush': ('boss_rush_mod.c', 'normal_character_mod.c'),
    'superbomberman5.extra-characters.characters': EXTRA,
    'superbomberman5.gold.battle': ('gold_battle_mod.c',),
    'superbomberman5.louie.improvements': ('louie_mod.c', 'clock_mounts.c'),
    'superbomberman5.normal.characters': ('normal_character_mod.c',),
    'superbomberman5.normal.coop': ('normal_coop_mod.c',),
    'superbomberman5.normal.coop.corner-spawns': ('normal_coop_mod.c',),
    'superbomberman5.normal.hud-faces': ('normal_hud_mod.c',),
    'superbomberman5.normal.infinite-lives': ('infinite_lives_mod.c',),
    'superbomberman5.normal.infinite-time': ('infinite_time_mod.c',),
    'superbomberman5.pause.menu': ('pause_menu_mod.c',),
    'superbomberman5.ptbr.menus': ('ptbr_font_locations.h',),
    'superbomberman5.selection.colors': ('selection_color_mod.c',),
}
# Tables the mods read per ROM rather than assume.
PER_ROM_DATA = {0xc01c96, 0xc01b0f}


def sites_of(name: str) -> set[int]:
    text = (ROOT / 'src' / name).read_text(encoding='utf-8', errors='replace')
    if name == 'ptbr_font_locations.h':  # Already file offsets.
        return {int(x, 16) for x in re.findall(r'\b0x[0-9a-fA-F]{4,6}\b', text)}
    pcs = {int(x, 16) for x in re.findall(r'\b0x[cC][0-7][0-9a-fA-F]{4}\b', text)}
    return {pc & 0x3fffff for pc in pcs - PER_ROM_DATA}


def main() -> int:
    if len(sys.argv) != 2:
        print(f'usage: {sys.argv[0]} <supported rom>', file=sys.stderr)
        return 2
    raw = pathlib.Path(sys.argv[1]).read_bytes()
    image = raw[512:] if len(raw) % 1024 == 512 else raw
    identity = (ROOT / 'rom_identity.txt').read_text(encoding='utf-8')
    wanted = re.search(r'expected_sha256\s*=\s*(\w+)', identity)[1].lower()
    if hashlib.sha256(image).hexdigest() != wanted:
        print('this needs the ROM named by rom_identity.txt', file=sys.stderr)
        return 1
    arrays, rows = [], []
    for index, (plugin, sources) in enumerate(sorted(PLUGINS.items())):
        sites = sorted(set().union(*(sites_of(s) for s in sources)))
        crc = zlib.crc32(b''.join(image[s:s + 4] for s in sites))
        body = ','.join(f'0x{s:06x}' for s in sites)
        arrays.append(f'static const uint32_t kSites{index}[] = {{{body}}};')
        rows.append(f'    {{"{plugin}", kSites{index}, {len(sites)}u, 0x{crc:08x}u}},')
    out = ['/* Generated by tools/gen-rom-probes.py. Addresses and digests only. */', *arrays,
           'static const Sb5RomProbe kRomProbes[] = {', *rows, '};', '']
    (ROOT / 'src/rom_probes.h').write_text('\n'.join(out), encoding='utf-8', newline='\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
