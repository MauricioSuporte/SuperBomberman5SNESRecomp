#!/usr/bin/env python3
"""Boss Rush online ranking: maintainer and CI helper.

The ranking lives in one Discord message (the "board") that the game edits
through a channel webhook; new top-5 times also post a notification there.
The webhook URL is a credential: it is kept in the repository secrets
BOSS_RUSH_WEBHOOK / BOSS_RUSH_BOARD, never in Git, and CI writes it into the
release packages as boss_rush_ranking.cfg. Anyone who unpacks a release can
read it, so rotate the webhook (and the secrets) if the channel is abused.

  Create the board once (prints the message id for BOSS_RUSH_BOARD):
      BOSS_RUSH_WEBHOOK=<webhook url> python tools/boss-rush-ranking.py --create-board
  Add the configuration to a release ZIP (CI; skipped without the secrets):
      python tools/boss-rush-ranking.py --add-to-zip dist/<package>.zip
  Check that the webhook can read the board (CI, before publishing):
      python tools/boss-rush-ranking.py --check
  Remove one time (moderation; the workflow "Boss Rush ranking" runs it):
      python tools/boss-rush-ranking.py --remove 2:1 --expect-time 08:34.31

Neither command prints the webhook URL.
"""
import argparse
import json
import os
import re
import sys
import urllib.request
import zipfile
from pathlib import Path

# Discord asks API clients for this User-Agent form; the game sends the same.
USER_AGENT = 'DiscordBot (https://github.com/MauricioSuporte/SuperBomberman5SNESRecomp, 1)'
WEBHOOK_RE = re.compile(r'^https://(?:(?:ptb|canary)\.)?discord(?:app)?\.com/api/' r'webhooks/\d+/[A-Za-z0-9_\-]+$')
CONFIG_NAME = 'boss_rush_ranking.cfg'
EMPTY_BOARD = {
    'content': '\U0001F3C6 **Boss Rush — ranking**',
    'allowed_mentions': {'parse': []},
    'embeds': [{
        'title': f'Boss Rush — {n} {"jogadores" if n > 1 else "jogador"} / {n} {"players" if n > 1 else "player"}',
        'description': 'Sem tempos ainda / No times yet',
        'footer': {'text': f'sb5br1 c={n}'},
    } for n in range(1, 6)],
}


def webhook_from_env() -> str | None:
    url = os.environ.get('BOSS_RUSH_WEBHOOK', '').strip().rstrip('/')
    return url if WEBHOOK_RE.match(url) else None


def create_board() -> int:
    url = webhook_from_env()
    if not url:
        print('Set BOSS_RUSH_WEBHOOK to the channel webhook URL (Discord: channel settings > Integrations > Webhooks).')
        return 2
    request = urllib.request.Request(url + '?wait=true', data=json.dumps(EMPTY_BOARD).encode('utf-8'),
                                     headers={'Content-Type': 'application/json', 'User-Agent': USER_AGENT},
                                     method='POST')
    with urllib.request.urlopen(request, timeout=20) as response:
        message = json.loads(response.read().decode('utf-8'))
    print('Board message created. Store its id as the BOSS_RUSH_BOARD secret:')
    print(message['id'])
    print('Tip: pin the message in the channel so players find it.')
    return 0


def add_to_zip(path: Path) -> int:
    url = webhook_from_env()
    board = os.environ.get('BOSS_RUSH_BOARD', '').strip()
    if not url or not re.fullmatch(r'\d{5,30}', board):
        print('Boss Rush ranking secrets not set: package left without an online ranking.')
        return 0
    with zipfile.ZipFile(path) as archive:
        names = archive.namelist()
    roots = {name.split('/')[0] for name in names}
    if len(roots) != 1:
        raise SystemExit('Expected a single package directory.')
    target = roots.pop() + '/' + CONFIG_NAME
    if target in names:
        raise SystemExit(f'{CONFIG_NAME} already in the package')
    with zipfile.ZipFile(path, 'a', zipfile.ZIP_DEFLATED) as archive:
        archive.writestr(target, f'# Boss Rush online ranking (Discord webhook). Generated by the release workflow.\n'
                                 f'webhook={url}\nboard={board}\n')
    print(f'Boss Rush ranking configuration added to {path.name}.')
    return 0


def annotate(level: str, text: str) -> None:
    """A GitHub Actions annotation (readable through the API, unlike logs)."""
    print(f'::{level}::{text}' if os.environ.get('GITHUB_ACTIONS') else text)


def curl_get(url: str) -> tuple[int, str]:
    """The game's request: curl with a config file (never the URL on the command line)."""
    import shutil, subprocess, tempfile
    if not shutil.which('curl'):
        return -1, 'curl not found'
    with tempfile.TemporaryDirectory() as tmp:
        cfg = Path(tmp) / 'req.txt'
        cfg.write_text(f'url = "{url}"\nrequest = "GET"\nsilent\nshow-error\nmax-time = 12\nconnect-timeout = 6\n'
                       f'header = "User-Agent: {USER_AGENT}"\nwrite-out = "\\n%{{http_code}}"\n')
        out = subprocess.run(['curl', '-K', str(cfg)], capture_output=True, text=True)
    body, _, code = out.stdout.rpartition('\n')
    return (int(code) if code.isdigit() else 0), body if code.isdigit() else out.stderr.strip()


def check() -> int:
    url = webhook_from_env()
    board = os.environ.get('BOSS_RUSH_BOARD', '').strip()
    if not url or not re.fullmatch(r'\d{5,30}', board):
        annotate('warning', 'Boss Rush ranking secrets not set (or malformed): packages ship without the online ranking.')
        return 0
    code, body = curl_get(f'{url}/messages/{board}')
    if code != 200:
        snippet = re.sub(r'https?://\S+', '<url>', body)[:300].replace('\n', ' ')
        annotate('error', f'Boss Rush ranking board not readable with curl: HTTP {code}: {snippet}')
        return 1
    found = sorted(int(m) for m in re.findall(r'sb5br1 c=([1-5])', body))
    if found != [1, 2, 3, 4, 5]:
        annotate('error', f'Boss Rush ranking board has categories {found}, expected 1-5.')
        return 1
    annotate('notice', 'Boss Rush ranking board readable through the webhook (5 categories).')
    return 0

# ---- the board, as the game writes it (src/boss_rush_ranking.c) ----------
CHARACTERS = [None, 'Bomberman', 'Bomber Woof', 'Dave Bomber', 'Gary Bomber', 'Pirate Bomber',
              'Muscle Bomber', 'Iron Mask Bomber', 'Baron Bombano', 'Plunder Bomber', 'Subordinate Bomber',
              'Honey', 'Kotetsu', 'Bomberman (SB4)', 'Hammer Bomber', 'Jet Bomber', 'Lady Bomber', 'Bazooka Bomber',
              'Bomber Great', 'Terrorin']
COLORS = [0xf5c542, 0x42a5f5, 0x66bb6a, 0xab47bc, 0xef5350]


def format_time(frames: int) -> str:
    cs = frames * 100 // 60
    return f'{min(cs // 6000, 99):02d}:{cs // 100 % 60:02d}.{cs % 100:02d}'


def parse_board(message: dict) -> dict[int, list[dict]]:
    """Categories 1-5 -> entries, from each embed footer's "sb5br1 c=N ..." data."""
    board = {c: [] for c in range(1, 6)}
    for embed in message.get('embeds', []):
        text = (embed.get('footer') or {}).get('text', '')
        m = re.fullmatch(r'sb5br1 c=([1-5])((?: \S+)*)', text)
        if not m:
            continue
        category = int(m.group(1))
        for token in m.group(2).split():
            frames, date, online, players = token.split(',', 3)
            entry = {'frames': int(frames), 'date': '' if date == '-' else date, 'online': online == '1', 'players': []}
            for p in players.split(';'):
                name, _, choice = p.rpartition('~')
                raw = re.sub(rb'%([0-9A-Fa-f]{2})', lambda h: bytes([int(h.group(1), 16)]), name.encode('utf-8'))
                entry['players'].append({'name': raw.decode('utf-8', 'replace'), 'choice': int(choice)})
            board[category].append(entry)
    return board


def _md(name: str) -> str:
    return ''.join('\\' + ch if ch in '\\*_~`|>[]()#@:' else ch for ch in name)


def _data_name(name: str) -> str:
    out = bytearray()
    for b in name.encode('utf-8'):
        if b <= 0x20 or b == 0x7f or b in b'%,;~|"\\':
            out += b'%%%02X' % b
        else:
            out.append(b)
    return out.decode('utf-8')


def category_embed(board: dict, category: int) -> dict:
    n = category
    entries = board[n]
    lines = []
    for rank, e in enumerate(entries, 1):
        who = ', '.join(_md(p['name']) + (f' ({CHARACTERS[p["choice"]] or "?"})' if p['choice'] else '')
                        for p in e['players'])
        lines.append(f'**{rank}.** `{format_time(e["frames"])}` {who} \u00b7 {"online" if e["online"] else "offline"}'
                     f' \u00b7 {e["date"] or "?"}\n')
    data = ''.join(f' {e["frames"]},{e["date"] or "-"},{1 if e["online"] else 0},'
                   + ';'.join(f'{_data_name(p["name"])}~{p["choice"]}' for p in e['players']) for e in entries)
    return {'color': COLORS[n - 1],
            'title': f'Boss Rush \u2014 {n} {"jogadores" if n > 1 else "jogador"} / {n} {"players" if n > 1 else "player"}',
            'description': ''.join(lines) or 'Sem tempos ainda / No times yet',
            'footer': {'text': f'sb5br1 c={n}{data}'}}


def board_payload(board: dict) -> dict:
    return {'content': '\U0001F3C6 **Boss Rush \u2014 ranking**', 'allowed_mentions': {'parse': []},
            'embeds': [category_embed(board, c) for c in range(1, 6)]}


def remove(spec: str, expect_time: str) -> int:
    url = webhook_from_env()
    board_id = os.environ.get('BOSS_RUSH_BOARD', '').strip()
    m = re.fullmatch(r'([1-5]):([1-5])', spec or '')
    if not url or not re.fullmatch(r'\d{5,30}', board_id) or not m:
        annotate('error', 'Need the BOSS_RUSH_WEBHOOK/BOSS_RUSH_BOARD secrets and --remove CATEGORY:RANK (1-5:1-5).')
        return 2
    category, rank = int(m.group(1)), int(m.group(2))
    code, body = curl_get(f'{url}/messages/{board_id}')
    if code != 200:
        annotate('error', f'Board not readable: HTTP {code}')
        return 1
    board = parse_board(json.loads(body))
    entries = board[category]
    if rank > len(entries):
        annotate('error', f'Category {category}P has {len(entries)} time(s); nothing at #{rank}.')
        return 1
    entry = entries[rank - 1]
    shown = format_time(entry['frames'])
    if expect_time and expect_time != shown:
        annotate('error', f'{category}P #{rank} is {shown}, not {expect_time}: nothing removed.')
        return 1
    del entries[rank - 1]
    data = json.dumps(board_payload(board)).encode('utf-8')
    request = urllib.request.Request(f'{url}/messages/{board_id}', data=data, method='PATCH',
                                     headers={'Content-Type': 'application/json', 'User-Agent': USER_AGENT})
    try:
        with urllib.request.urlopen(request, timeout=20) as response:
            response.read()
    except Exception as error:  # never print the URL
        annotate('error', f'Board update failed: {type(error).__name__} {getattr(error, "code", "")}'.strip())
        return 1
    names = ', '.join(p['name'] for p in entry['players'])
    annotate('notice', f'Removed {category}P #{rank}: {shown} ({names}, {entry["date"]}).')
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--create-board', action='store_true')
    group.add_argument('--add-to-zip', type=Path)
    group.add_argument('--check', action='store_true')
    group.add_argument('--remove', metavar='CATEGORY:RANK')
    parser.add_argument('--expect-time', default='', help='refuse unless that entry shows this time (MM:SS.CC)')
    args = parser.parse_args()
    if args.check:
        return check()
    if args.remove:
        return remove(args.remove, args.expect_time)
    return create_board() if args.create_board else add_to_zip(args.add_to_zip)


if __name__ == '__main__':
    sys.exit(main())
